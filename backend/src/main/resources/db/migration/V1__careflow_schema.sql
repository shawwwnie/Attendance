CREATE TABLE recipient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    name VARCHAR(40) NOT NULL,
    care_grade INTEGER NOT NULL CHECK (care_grade BETWEEN 1 AND 5),
    daily_fee BIGINT NOT NULL CHECK (daily_fee BETWEEN 1000 AND 1000000),
    copay_basis_points INTEGER NOT NULL CHECK (copay_basis_points BETWEEN 0 AND 10000),
    UNIQUE (id, center_id)
);

CREATE TABLE visit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    recipient_id BIGINT NOT NULL,
    service_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PLANNED', 'COMPLETED', 'CANCELLED')),
    CHECK (end_time > start_time),
    FOREIGN KEY (recipient_id, center_id) REFERENCES recipient(id, center_id),
    UNIQUE (center_id, recipient_id, service_date),
    UNIQUE (id, center_id)
);
CREATE INDEX idx_visit_center_date_status ON visit(center_id, service_date, status);

CREATE TABLE invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    recipient_id BIGINT NOT NULL,
    billing_month VARCHAR(7) NOT NULL,
    total_amount BIGINT NOT NULL CHECK (total_amount > 0),
    copay_amount BIGINT NOT NULL CHECK (copay_amount >= 0 AND copay_amount <= total_amount),
    paid_amount BIGINT NOT NULL DEFAULT 0 CHECK (paid_amount >= 0 AND paid_amount <= copay_amount),
    FOREIGN KEY (recipient_id, center_id) REFERENCES recipient(id, center_id),
    UNIQUE (center_id, recipient_id, billing_month),
    UNIQUE (id, center_id)
);
CREATE INDEX idx_invoice_center_month ON invoice(center_id, billing_month);

CREATE TABLE invoice_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    invoice_id BIGINT NOT NULL,
    visit_id BIGINT NOT NULL UNIQUE,
    service_date DATE NOT NULL,
    daily_fee BIGINT NOT NULL CHECK (daily_fee > 0),
    copay_basis_points INTEGER NOT NULL CHECK (copay_basis_points BETWEEN 0 AND 10000),
    copay_amount BIGINT NOT NULL CHECK (copay_amount >= 0 AND copay_amount <= daily_fee),
    FOREIGN KEY (invoice_id, center_id) REFERENCES invoice(id, center_id),
    FOREIGN KEY (visit_id, center_id) REFERENCES visit(id, center_id)
);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    invoice_id BIGINT NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    amount BIGINT NOT NULL CHECK (amount > 0),
    memo VARCHAR(100) NOT NULL,
    FOREIGN KEY (invoice_id, center_id) REFERENCES invoice(id, center_id),
    UNIQUE (center_id, idempotency_key)
);

CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    actor VARCHAR(40) NOT NULL,
    action VARCHAR(40) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    entity_id BIGINT NOT NULL,
    detail VARCHAR(250) NOT NULL
);
CREATE INDEX idx_audit_center_created ON audit_event(center_id, created_at DESC, id DESC);
